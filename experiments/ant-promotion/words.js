export const { t, lang, setLang, apply, langs } = words(tables);

// The translation of an English identifier under a prefix, or the English itself when there is none.
export function tx(prefix, english) {
  const key = prefix + english, s = t(key);
  return typeof s === 'string' && s !== key ? s : english;
}
export const animal = name => tx('animal.', name);
export const skill = label => tx('skill.', label);
export const trait = text => tx('trait.', text);
export const line = text => tx('line.', text);
export const title = text => tx('title.', text);
export const sight = text => (lang() === 'en' ? text : text.split(', ').map(p => tx('sight.', p)).join(', '));
// The rival's saved name is "Old Scar the Wolf". Translated only when both parts are known; otherwise the saved text.
export function rivalName(name) {
  if (lang() === 'en' || typeof name !== 'string') return name;
  const m = /^(.+) the (.+)$/.exec(name);
  if (!m) return name;
  const known = key => Object.prototype.hasOwnProperty.call(tables[lang()] || {}, key);
  return known('epithet.' + m[1]) && known('animal.' + m[2]) ? `${tx('epithet.', m[1])} ${animal(m[2])}` : name;
}

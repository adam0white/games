export const { t, lang, apply, setLang, langs } = words(tables);

const formats = Object.fromEntries(langs.map(code => [code, {
  number: new Intl.NumberFormat(code),
  padded: new Intl.NumberFormat(code, { minimumIntegerDigits: 2, useGrouping: false }),
  date: new Intl.DateTimeFormat(code, { dateStyle: 'medium', timeZone: 'UTC' }),
}]));

export const number = n => formats[lang()].number.format(n);
export const padded = n => formats[lang()].padded.format(n);
export const date = day => formats[lang()].date.format(new Date(day + 'T00:00:00Z'));
export const count = (key, n) => t(key, { n: number(n) });
export const time = seconds => t('time', { minutes: number(Math.floor(seconds / 60)), seconds: padded(seconds % 60) });

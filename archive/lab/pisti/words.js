export function dateLabel(iso) {
  const d = new Date(iso + 'T00:00:00Z');
  return Number.isFinite(d.getTime()) ? d.toLocaleDateString(lang(), { dateStyle: 'medium', timeZone: 'UTC' }) : iso;
}

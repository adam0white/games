export const { t, lang, apply, setLang } = words(tables);

const formats = {};
export function num(value) {
  const code = lang();
  return (formats[code] ??= new Intl.NumberFormat(code)).format(value);
}
const dates = {};
export function dateLabel(iso) {
  const code = lang(), d = new Date(iso + 'T00:00:00Z');
  if (!Number.isFinite(d.getTime())) return iso;
  return (dates[code] ??= new Intl.DateTimeFormat(code, { dateStyle: 'medium', timeZone: 'UTC' })).format(d);
}

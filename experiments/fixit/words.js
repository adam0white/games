export const { t, lang, apply, setLang } = words(tables);

const formats = Object.fromEntries(Object.keys(tables).map(code => [code, {
  number: new Intl.NumberFormat(code),
  date: new Intl.DateTimeFormat(code, { dateStyle: 'medium', timeZone: 'UTC' }),
}]));
export const num = value => formats[lang()].number.format(value);
export const seconds = value => t('seconds', { n: num(value) });
export const starsLabel = value => t(lang() === 'en' && value === 1 ? 'oneStar' : 'stars', { n: num(value) });
export function dateLabel(iso) {
  const date = new Date(iso + 'T00:00:00Z');
  return Number.isFinite(date.getTime()) ? formats[lang()].date.format(date) : iso;
}

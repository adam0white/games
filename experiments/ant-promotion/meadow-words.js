// The key for a trait, with stay split by its sign.
export const traitKey = (k, sign) => (k === 'stay' ? `stay${sign < 0 ? '-' : '+'}` : k);
export function complete() {
  const need = [];
  for (const k of ['grass', 'stay+', 'stay-', 'lead', 'shake', 'wary', 'bold']) need.push(`meadow.trait.${k}`, `meadow.up.${k}`, `meadow.down.${k}`);
  return Object.keys(en).every(k => tr[k]) && need.every(k => en[k] && tr[k]) && Object.keys(tr).every(k => en[k]);
}
